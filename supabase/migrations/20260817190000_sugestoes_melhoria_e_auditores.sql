create or replace function public.save_auditor_cadastrado(
  p_password text,
  p_id bigint,
  p_origem text,
  p_origem_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_origem text := lower(btrim(coalesce(p_origem, '')));
  v_nome text;
  v_cargo text;
  v_setor text;
begin
  if not public.admin_password_ok(p_password) then
    raise exception 'Senha administrativa inválida';
  end if;

  if v_origem not in ('lideranca', 'operacional') or p_origem_id is null then
    raise exception 'Selecione um colaborador cadastrado';
  end if;

  if v_origem = 'lideranca' then
    select lider.nome, lider.cargo, lider.setor
    into v_nome, v_cargo, v_setor
    from public.liderancas lider
    where lider.id = p_origem_id
      and lider.ativo;
  else
    select colaborador.subordinado, colaborador.cargo, colaborador.setor
    into v_nome, v_cargo, v_setor
    from public.subordinacoes colaborador
    where colaborador.id = p_origem_id
      and colaborador.ativo;
  end if;

  if v_nome is null then
    raise exception 'O auditor precisa ser uma liderança ou um colaborador operacional ativo';
  end if;

  if exists (
    select 1
    from public.auditores_cadastrados auditor
    where auditor.ativo
      and lower(btrim(auditor.nome)) = lower(btrim(v_nome))
      and (p_id is null or auditor.id <> p_id)
  ) then
    raise exception 'Este colaborador já está cadastrado como auditor';
  end if;

  if p_id is null then
    insert into public.auditores_cadastrados (origem, origem_id, nome, cargo, setor)
    values (v_origem, p_origem_id, v_nome, v_cargo, v_setor)
    returning id into v_id;
  else
    update public.auditores_cadastrados
    set origem = v_origem,
        origem_id = p_origem_id,
        nome = v_nome,
        cargo = v_cargo,
        setor = v_setor,
        ativo = true,
        updated_at = now()
    where id = p_id
    returning id into v_id;

    if v_id is null then
      raise exception 'Cadastro de auditor não encontrado';
    end if;
  end if;

  return v_id;
end;
$$;

create or replace function public.delete_auditor_cadastrado(
  p_password text,
  p_id bigint
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_afetados integer;
begin
  if not public.admin_password_ok(p_password) then
    raise exception 'Senha administrativa inválida';
  end if;

  update public.auditores_cadastrados
  set ativo = false,
      updated_at = now()
  where id = p_id
    and ativo;

  get diagnostics v_afetados = row_count;
  return v_afetados > 0;
end;
$$;

