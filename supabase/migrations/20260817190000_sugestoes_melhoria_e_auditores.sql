create table public.auditores_cadastrados (
  id bigint generated by default as identity primary key,
  origem text not null,
  origem_id bigint not null,
  nome text not null,
  cargo text not null,
  setor text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint auditores_cadastrados_origem_check
    check (origem in ('lideranca', 'operacional')),
  constraint auditores_cadastrados_nome_not_blank check (btrim(nome) <> ''),
  constraint auditores_cadastrados_cargo_not_blank check (btrim(cargo) <> ''),
  constraint auditores_cadastrados_setor_not_blank check (btrim(setor) <> '')
);

create unique index auditores_cadastrados_origem_ativo_uidx
  on public.auditores_cadastrados (origem, origem_id)
  where ativo;

create unique index auditores_cadastrados_nome_ativo_uidx
  on public.auditores_cadastrados (lower(btrim(nome)))
  where ativo;

create index auditores_cadastrados_setor_nome_ativo_idx
  on public.auditores_cadastrados (setor, nome)
  where ativo;

alter table public.auditores_cadastrados enable row level security;

create policy "Auditores ativos são públicos para seleção"
  on public.auditores_cadastrados
  for select
  to anon, authenticated
  using (ativo);

revoke all on table public.auditores_cadastrados from anon, authenticated;
grant select on table public.auditores_cadastrados to anon, authenticated;
grant all on table public.auditores_cadastrados to service_role;

create view public.auditores_publicos
with (security_invoker = true)
as
select id, origem, origem_id, nome, cargo, setor, created_at, updated_at
from public.auditores_cadastrados
where ativo;

