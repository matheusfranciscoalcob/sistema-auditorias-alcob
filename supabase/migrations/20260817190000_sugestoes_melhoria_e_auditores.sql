create view public.sugestoes_melhoria_publicas
with (security_invoker = true)
as
select
  sugestao.id,
  sugestao.titulo,
  sugestao.descricao,
  sugestao.status,
  sugestao.created_at,
  sugestao.updated_at,
  coalesce(autores.itens, '[]'::jsonb) as autores,
  coalesce(auditorias.ids, array[]::bigint[]) as auditoria_ids,
  coalesce(auditorias.itens, '[]'::jsonb) as auditorias,
  coalesce(historico.itens, '[]'::jsonb) as historico
from public.sugestoes_melhoria sugestao
left join lateral (
  select jsonb_agg(
    jsonb_build_object(
      'origem', autor.origem,
      'origemId', autor.origem_id,
      'nome', autor.nome,
      'cargo', autor.cargo,
      'setor', autor.setor
    )
    order by autor.nome
  ) as itens
  from public.sugestoes_melhoria_autores autor
  where autor.sugestao_id = sugestao.id
) autores on true
left join lateral (
  select
    array_agg(vinculo.auditoria_id order by auditoria.audit_date desc, vinculo.auditoria_id desc) as ids,
    jsonb_agg(
      jsonb_build_object(
        'id', auditoria.audit_id,
        'type', auditoria.type,
        'team', auditoria.team,
        'date', auditoria.audit_date,
        'score', auditoria.score,
        'supervisorName', auditoria.supervisor_name,
        'auditedRole', auditoria.audited_role
      )
      order by auditoria.audit_date desc, vinculo.auditoria_id desc
    ) as itens
  from public.sugestoes_melhoria_auditorias vinculo
  join public.auditoria_resultados auditoria
    on auditoria.audit_id = vinculo.auditoria_id
  where vinculo.sugestao_id = sugestao.id
) auditorias on true
left join lateral (
  select jsonb_agg(
    jsonb_build_object(
      'status', evento.status,
      'observacao', evento.observacao,
      'data', evento.created_at
    )
    order by evento.created_at desc, evento.id desc
  ) as itens
  from public.sugestoes_melhoria_status_historico evento
  where evento.sugestao_id = sugestao.id
) historico on true;

revoke all on table public.sugestoes_melhoria_publicas from public;
grant select on table public.sugestoes_melhoria_publicas to anon, authenticated, service_role;

create or replace function public.save_sugestao_melhoria(
  p_password text,
  p_id bigint,
  p_titulo text,
  p_descricao text,
  p_autores text[],
  p_auditoria_ids bigint[],
  p_status text,
  p_observacao_status text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_titulo text := btrim(coalesce(p_titulo, ''));
  v_descricao text := btrim(coalesce(p_descricao, ''));
  v_status text := coalesce(nullif(btrim(p_status), ''), 'Registrada');
  v_observacao text := nullif(btrim(coalesce(p_observacao_status, '')), '');
  v_status_anterior text;
  v_auditoria_ids bigint[];
begin
  if not public.admin_password_ok(p_password) then
    raise exception 'Senha administrativa inválida';
  end if;

  if v_titulo = '' or v_descricao = '' then
    raise exception 'Título e descrição da sugestão são obrigatórios';
  end if;

  if v_status not in ('Registrada', 'Em análise', 'Aprovada', 'Em implementação', 'Concluída', 'Não aprovada') then
    raise exception 'Status da sugestão inválido';
  end if;

  if coalesce(cardinality(p_autores), 0) = 0 then
    raise exception 'Selecione pelo menos um colaborador como autor da ideia';
  end if;

  if exists (
    select 1
    from unnest(p_autores) selecionado(token)
    where selecionado.token !~ '^(lideranca|operacional):[0-9]+$'
  ) then
    raise exception 'Existe um autor inválido na seleção';
  end if;

  if exists (
    select 1
    from unnest(p_autores) selecionado(token)
    where case split_part(selecionado.token, ':', 1)
      when 'lideranca' then not exists (
        select 1
        from public.liderancas lider
        where lider.id = split_part(selecionado.token, ':', 2)::bigint
          and lider.ativo
      )
      when 'operacional' then not exists (
        select 1
        from public.subordinacoes colaborador
        where colaborador.id = split_part(selecionado.token, ':', 2)::bigint
          and colaborador.ativo
      )
      else true
    end
  ) then
    raise exception 'Todos os autores precisam permanecer cadastrados e ativos';
  end if;

  select coalesce(array_agg(distinct id order by id), array[]::bigint[])
  into v_auditoria_ids
  from unnest(coalesce(p_auditoria_ids, array[]::bigint[])) selecionada(id)
  where id is not null;

  if exists (
    select 1
    from unnest(v_auditoria_ids) selecionada(id)
    left join public.auditorias auditoria on auditoria.audit_id = selecionada.id
    where auditoria.audit_id is null
  ) then
    raise exception 'Uma das auditorias de origem não foi encontrada';
  end if;

  if p_id is null then
    insert into public.sugestoes_melhoria (titulo, descricao, status)
    values (v_titulo, v_descricao, v_status)
    returning id into v_id;
  else
    select status
    into v_status_anterior
    from public.sugestoes_melhoria
    where id = p_id;

    if v_status_anterior is null then
      raise exception 'Sugestão de melhoria não encontrada';
    end if;

    update public.sugestoes_melhoria
    set titulo = v_titulo,
        descricao = v_descricao,
        status = v_status,
        updated_at = now()
    where id = p_id
    returning id into v_id;
  end if;

  delete from public.sugestoes_melhoria_autores where sugestao_id = v_id;

  insert into public.sugestoes_melhoria_autores (
    sugestao_id, origem, origem_id, nome, cargo, setor
  )
  select distinct on (lower(btrim(pessoa.nome)))
    v_id,
    pessoa.origem,
    pessoa.origem_id,
    pessoa.nome,
    pessoa.cargo,
    pessoa.setor
  from (
    select
      'lideranca'::text as origem,
      lider.id as origem_id,
      lider.nome,
      lider.cargo,
      lider.setor
    from unnest(p_autores) selecionado(token)
    join public.liderancas lider
      on split_part(selecionado.token, ':', 1) = 'lideranca'
     and lider.id = split_part(selecionado.token, ':', 2)::bigint
     and lider.ativo
    union all
    select
      'operacional'::text as origem,
      colaborador.id as origem_id,
      colaborador.subordinado as nome,
      colaborador.cargo,
      colaborador.setor
    from unnest(p_autores) selecionado(token)
    join public.subordinacoes colaborador
      on split_part(selecionado.token, ':', 1) = 'operacional'
     and colaborador.id = split_part(selecionado.token, ':', 2)::bigint
     and colaborador.ativo
  ) pessoa
  order by lower(btrim(pessoa.nome)), pessoa.origem, pessoa.origem_id;

  if not exists (
    select 1
    from public.sugestoes_melhoria_autores autor
    where autor.sugestao_id = v_id
  ) then
    raise exception 'Selecione pelo menos um colaborador como autor da ideia';
  end if;

  delete from public.sugestoes_melhoria_auditorias where sugestao_id = v_id;

  insert into public.sugestoes_melhoria_auditorias (sugestao_id, auditoria_id)
  select v_id, selecionada.id
  from unnest(v_auditoria_ids) selecionada(id);

  if p_id is null or v_status_anterior is distinct from v_status or v_observacao is not null then
    insert into public.sugestoes_melhoria_status_historico (sugestao_id, status, observacao)
    values (
      v_id,
      v_status,
      coalesce(v_observacao, case when p_id is null then 'Sugestão registrada no sistema.' else null end)
    );
  end if;

  return v_id;
end;
$$;

