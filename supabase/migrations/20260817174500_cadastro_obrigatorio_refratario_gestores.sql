insert into public.liderancas (nome, cargo, setor, superior_id)
select cadastro.nome, 'Gerente', cadastro.setor, diretor.id
from (
  values
    ('João Paulo'::text, 'engenharia'::text),
    ('José Roberto Madalena'::text, 'qualidade_laboratorio'::text),
    ('Japa'::text, 'producao'::text),
    ('Fernando'::text, 'prensa'::text)
) as cadastro(nome, setor)
cross join lateral (
  select id
  from public.liderancas
  where ativo
    and cargo = 'Diretor'
    and lower(btrim(nome)) = 'wagner'
  order by id
  limit 1
) diretor
where not exists (
  select 1
  from public.liderancas existente
  where existente.ativo
    and existente.cargo = 'Gerente'
    and lower(btrim(existente.nome)) = lower(btrim(cadastro.nome))
);

update public.liderancas gerente
set setor = cadastro.setor,
    superior_id = diretor.id,
    updated_at = now()
from (
  values
    ('João Paulo'::text, 'engenharia'::text),
    ('José Roberto Madalena'::text, 'qualidade_laboratorio'::text),
    ('Japa'::text, 'producao'::text),
    ('Fernando'::text, 'prensa'::text)
) as cadastro(nome, setor)
cross join lateral (
  select id
  from public.liderancas
  where ativo
    and cargo = 'Diretor'
    and lower(btrim(nome)) = 'wagner'
  order by id
  limit 1
) diretor
where gerente.ativo
  and gerente.cargo = 'Gerente'
  and lower(btrim(gerente.nome)) = lower(btrim(cadastro.nome));

update public.liderancas gestor
set superior_id = gerente.id,
    updated_at = now()
from public.liderancas gerente
where gestor.ativo
  and gestor.cargo = 'Gestor'
  and lower(btrim(gestor.setor)) in ('forno', 'laminacao')
  and gerente.ativo
  and gerente.cargo = 'Gerente'
  and lower(btrim(gerente.nome)) = 'japa';
